import type { TokenGroup } from '../data/token.ts';
import { cssVariableName } from './css-variable-name.ts';
import { flattenTokens } from './flatten-tokens.ts';

const HEADER = '// Generated by `bun run build` from tokens/. Do not edit by hand.';

/**
 * A TypeScript module for the framework ports: every token name (`color.surface`) with the CSS
 * variable that holds it, so a port refers to tokens by name and the compiler catches typos.
 */
export function renderTypescript(base: TokenGroup, themes: readonly TokenGroup[]): string {
  const paths = [base, ...themes].flatMap((tree) => flattenTokens(tree).map(({ path }) => path));
  const unique = [...new Map(paths.map((path) => [path.join('.'), path])).values()];
  const lines = unique.map((path) => `  '${path.join('.')}': 'var(${cssVariableName(path)})',`);
  return `${HEADER}\nexport const tokens = {\n${lines.join('\n')}\n} as const;\n\nexport type TokenName = keyof typeof tokens;\n`;
}
