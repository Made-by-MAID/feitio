import { describe, expect, test } from 'bun:test';
import type { Theme, TokenGroup } from '../data/token.ts';
import { renderCss } from './render-css.ts';

const base: TokenGroup = {
  space: { $type: 'dimension', '1': { $value: { value: 0.25, unit: 'rem' } } },
};
const color = (l: number) => ({ $value: { colorSpace: 'oklch', components: [l, 0, 0] } }) as const;
const themes: Theme[] = [
  { name: 'casa', mode: 'light', tokens: { color: { $type: 'color', surface: color(0.96) } } },
  { name: 'casa', mode: 'dark', tokens: { color: { $type: 'color', surface: color(0.22) } } },
  { name: 'horta', mode: 'light', tokens: { color: { $type: 'color', surface: color(0.9) } } },
];

describe('renderCss', () => {
  const css = renderCss(base, themes, 'casa');

  test('says it is generated, so nobody edits it by hand', () => {
    expect(css.startsWith('/* Generated by `bun run build`')).toBe(true);
  });

  test('puts everything in the feitio.tokens layer', () => {
    expect(css).toContain('@layer feitio.tokens {');
  });

  test('declares a base token built on a theme token on every themed element', () => {
    const withShadow: TokenGroup = {
      shadow: {
        $type: 'shadow',
        lift: {
          $value: {
            color: '{color.shadow}',
            offsetX: { value: 5, unit: 'px' },
            offsetY: { value: 6, unit: 'px' },
            blur: { value: 0, unit: 'px' },
            spread: { value: 0, unit: 'px' },
          },
        },
      },
    };
    expect(renderCss(withShadow, [], 'casa')).toContain(
      ':root,\n  [data-theme],\n  [data-mode] {\n    --feitio-shadow-lift: 5px 6px 0px 0px var(--feitio-color-shadow);',
    );
  });

  test('writes base tokens on :root', () => {
    expect(css).toContain(':root {\n    --feitio-space-1: 0.25rem;\n  }');
  });

  test('the default theme by day also answers on a page with no data-theme', () => {
    expect(css).toContain(
      ':root,\n  [data-theme="casa"] {\n    --feitio-color-surface: oklch(96% 0 0);',
    );
  });

  test('a night version answers to data-mode="dark"', () => {
    expect(css).toContain(
      ':root:not([data-theme])[data-mode="dark"],\n  [data-theme="casa"][data-mode="dark"] {',
    );
  });

  test('the default night follows the system when the page does not choose', () => {
    expect(css).toContain(
      '@media (prefers-color-scheme: dark) {\n    :root:not([data-theme]):not([data-mode]),',
    );
  });

  test('another theme answers only to its own name', () => {
    expect(css).toContain(
      '\n  [data-theme="horta"] {\n    --feitio-color-surface: oklch(90% 0 0);',
    );
  });

  test('ends with a single newline', () => {
    expect(css.endsWith('}\n')).toBe(true);
  });
});
