import type { LinearRgb, Oklch } from '../data/oklch.ts';

/**
 * OKLCH to linear-light sRGB, through OKLab, with Björn Ottosson's matrices. Channels are not
 * clamped: a value outside 0..1 means the color is outside the sRGB gamut.
 */
export function oklchToLinearSrgb({ l, c, h }: Oklch): LinearRgb {
  const hue = (h * Math.PI) / 180;
  const a = c * Math.cos(hue);
  const b = c * Math.sin(hue);

  const lCone = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const mCone = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const sCone = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;

  return {
    r: 4.0767416621 * lCone - 3.3077115913 * mCone + 0.2309699292 * sCone,
    g: -1.2684380046 * lCone + 2.6097574011 * mCone - 0.3413193965 * sCone,
    b: -0.0041960863 * lCone - 0.7034186147 * mCone + 1.707614701 * sCone,
  };
}
